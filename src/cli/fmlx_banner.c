/* fmlx_banner.c — banner di avvio della CLI: big text "FastLLM" + identità e licenza.
 *
 * Il disegno del big text è il PORT dell'algoritmo di GMBasic (`native/gmb_runtime_c/
 * src/gmb_tui_bigtext.c`, stesso autore): un font 5x7 per lettere maiuscole e cifre, dove ogni
 * bit acceso diventa U+2588 (FULL BLOCK, UTF-8 `E2 96 88`) e ogni bit spento uno spazio, con una
 * colonna di gap fra i caratteri. Qui non c'è nessun widget/screen buffer: si scrive direttamente
 * su `FILE*`, che è tutto ciò che serve a una CLI.
 */
#include "fmlx_cli_internal.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define FMLX_VERSION "1.0"
#define FMLX_LICENSE "Apache License 2.0"
#define FMLX_AUTHOR "Gaetano Minardi"

